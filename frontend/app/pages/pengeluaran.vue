        <div style="margin-bottom: 1rem;">
          <label style="display: block; margin-bottom: 0.25rem;">Jenis Iuran / Nama Biaya</label>
          <input type="text" v-model="form.name" class="input" placeholder="Misal: Iuran Sampah, Internet" />
        </div>

        <div style="margin-bottom: 1rem;">

<template>
  <div class="page-container">
    <header class="page-header">
      <h1 class="page-title">Pengeluaran & Biaya</h1>
      <p class="page-subtitle">Kelola konfigurasi biaya operasional dan catat pengeluaran kosan Anda.</p>
    </header>

    <div class="material-card" style="margin-bottom: 2rem;">
      <div style="display: flex; justify-content: space-between; align-items: center; margin-bottom: 1.25rem;">
        <h2 style="color: var(--primary-color); margin: 0;">Konfigurasi Biaya Pengeluaran</h2>
        <button class="btn" @click="openConfigModal()">+ Tambah Konfigurasi</button>
      </div>

      <div class="table-container">
        <table class="data-table">
          <thead>
            <tr>
              <th>Jenis Iuran</th>
              <th>Nominal (Rp)</th>
              <th>Frekuensi</th>
              <th>Jadwal / Durasi</th>
              <th style="text-align: right;">Aksi</th>
            </tr>
          </thead>
          <tbody>
            <tr v-if="configs.length === 0">
              <td colspan="5" style="text-align: center; color: var(--text-muted);">Belum ada konfigurasi.</td>
            </tr>
            <tr v-for="cfg in configs" :key="cfg._id">
              <td style="font-weight: 500;">{{ cfg.name }}</td>
              <td>Rp {{ cfg.amount.toLocaleString('id-ID') }}</td>
              <td>{{ cfg.frequency }}</td>
              <td>
                <span v-if="cfg.frequency === 'Manual'">-</span>
                <span v-else-if="cfg.timingType === 'Fixed' && cfg.frequency === 'Bulanan'">Setiap tanggal {{ cfg.fixedDay }}</span>
                <span v-else-if="cfg.timingType === 'Fixed' && cfg.frequency === 'Mingguan'">Hari ke-{{ cfg.fixedDay }} tiap minggu</span>
                <span v-else-if="cfg.timingType === 'Fixed' && cfg.frequency === 'Harian'">Setiap hari</span>
                <span v-else>Setiap {{ cfg.duration }} {{ cfg.frequency === 'Bulanan' ? 'Bulan' : cfg.frequency === 'Mingguan' ? 'Minggu' : 'Hari' }}</span>
              </td>
              <td style="text-align: right; display: flex; gap: 0.5rem; justify-content: flex-end;">
                <button class="btn btn-sm" style="background: #0288d1; color: white;" @click="triggerConfig(cfg._id)" :disabled="triggeringId === cfg._id">PICU / CATAT</button>
                <button class="btn btn-sm" style="background: #ed6c02; color: white;" @click="openConfigModal(cfg)">Edit</button>
                <button class="btn btn-sm" style="background: var(--danger); color: white;" @click="deleteConfig(cfg._id)">Hapus</button>
              </td>
            </tr>
          </tbody>
        </table>
      </div>
    </div>

    <div class="material-card">
      <div style="display: flex; justify-content: space-between; align-items: center; margin-bottom: 1.25rem;">
        <h2 style="color: var(--primary-color); margin: 0;">Riwayat Pengeluaran</h2>
        <div style="display: flex; gap: 0.5rem; align-items: center;">
          <label style="font-weight: 500;">Filter Bulan:</label>
          <input type="month" v-model="filterMonth" class="input" style="width: auto; padding: 0.25rem 0.5rem;" @change="fetchHistory" />
        </div>
      </div>
      
      <div v-if="pendingHistory">Memuat riwayat...</div>
      <div v-else class="table-container">
        <table class="data-table">
          <thead>
            <tr>
              <th>Tanggal</th>
              <th>Kategori</th>
              <th>Deskripsi</th>
              <th>Nominal (Rp)</th>
              <th>Sistem</th>
              <th style="text-align: right;">Aksi</th>
            </tr>
          </thead>
          <tbody>
            <tr v-if="history.length === 0">
              <td colspan="6" style="text-align: center; color: var(--text-muted);">Belum ada riwayat pengeluaran di bulan ini.</td>
            </tr>
            <tr v-for="h in history" :key="h._id">
              <td>{{ new Date(h.date).toLocaleDateString('id-ID') }}</td>
              <td style="font-weight: 500;">{{ h.category }}</td>
              <td>{{ h.description }}</td>
              <td>Rp {{ h.amount.toLocaleString('id-ID') }}</td>
              <td>
                <span v-if="h.isAutoGenerated" class="status-badge status-active">Otomatis (Cron)</span>
                <span v-else class="status-badge status-booked">Manual</span>

<script setup lang="ts">
import { ref, onMounted } from 'vue';

const configs = ref<any[]>([]);
const history = ref<any[]>([]);
const filterMonth = ref('');

const pendingHistory = ref(false);
const showModal = ref(false);
const saving = ref(false);
const triggeringId = ref<string | null>(null);

const defaultForm = {
  _id: null,
  name: '',
  amount: 0,
  frequency: 'Manual',
  timingType: 'Duration',
  duration: 1,
  fixedDay: 1
};
const form = ref<any>({ ...defaultForm });

onMounted(() => {
  const d = new Date();
  filterMonth.value = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`;
  fetchConfigs();
  fetchHistory();
});

const fetchConfigs = async () => {
  try {
    const res = await fetch('http://localhost:3011/api/expenses/config');
    configs.value = await res.json();
  } catch (err) {
    console.error(err);
  }
};

const fetchHistory = async () => {
  pendingHistory.value = true;
  try {
    const res = await fetch(`http://localhost:3011/api/expenses?month=${filterMonth.value}`);
    history.value = await res.json();
  } catch (err) {
    console.error(err);
  }
  pendingHistory.value = false;
};

const openConfigModal = (cfg?: any) => {
  if (cfg) {
    form.value = { ...cfg };
  } else {
    form.value = { ...defaultForm };
  }
  showModal.value = true;
};

const saveConfig = async () => {
  if (!form.value.name || form.value.amount < 0) {
    alert('Mohon isi nama dan nominal yang valid.');
    return;
  }
  saving.value = true;
  try {
    let url = 'http://localhost:3011/api/expenses/config';
    let method = 'POST';
    if (form.value._id) {
      url += `/${form.value._id}`;
      method = 'PUT';
    }
    const res = await fetch(url, {
      method,
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(form.value)
    });
    if (!res.ok) throw new Error('Failed to save config');
    await fetchConfigs();
    showModal.value = false;
  } catch (err) {
    alert('Gagal menyimpan konfigurasi.');
  }
  saving.value = false;
};

const deleteConfig = async (id: string) => {
  if (!confirm('Yakin ingin menghapus konfigurasi ini? Ini tidak akan menghapus riwayat pengeluarannya.')) return;
  try {
    await fetch(`http://localhost:3011/api/expenses/config/${id}`, { method: 'DELETE' });
    await fetchConfigs();
  } catch (err) {
    alert('Gagal menghapus konfigurasi.');
  }
};

const triggerConfig = async (id: string) => {
  triggeringId.value = id;
  try {
    const res = await fetch('http://localhost:3011/api/expenses/trigger', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ configId: id })
    });
    if (!res.ok) {
      const errData = await res.json();
      throw new Error(errData.error || 'Failed to trigger');
    }
    alert('Pengeluaran berhasil dicatat!');
    await fetchHistory();
  } catch (err: any) {
    alert('Gagal mencatat: ' + err.message);
  }
  triggeringId.value = null;
};

const deleteExpense = async (id: string) => {
  if (!confirm('Hapus riwayat pengeluaran ini?')) return;
  try {
    await fetch(`http://localhost:3011/api/expenses/${id}`, { method: 'DELETE' });
    await fetchHistory();
  } catch (err) {
    alert('Gagal menghapus riwayat.');
  }
};
</script>


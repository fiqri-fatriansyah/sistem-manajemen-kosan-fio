          </div>

          <div v-else>
            <div v-if="form.frequency === 'Bulanan'">
              <label style="display: block; margin-bottom: 0.25rem;">Tanggal Potong (1-31)</label>
              <input type="number" min="1" max="31" v-model="form.fixedDay" class="input" />
            </div>
            <div v-else-if="form.frequency === 'Mingguan'">
              <label style="display: block; margin-bottom: 0.25rem;">Hari Potong (0 = Minggu, 1 = Senin, ... 6 = Sabtu)</label>
              <input type="number" min="0" max="6" v-model="form.fixedDay" class="input" />
            </div>
            <div v-else>
              <small class="text-muted">Akan dipotong setiap hari.</small>
            </div>
          </div>
        </div>

        <div style="display: flex; gap: 0.5rem; justify-content: flex-end; margin-top: 1.5rem;">
          <button class="btn" style="background: #e0e0e0; color: #333;" @click="showModal = false">Batal</button>
          <button class="btn" @click="saveConfig" :disabled="saving">Simpan</button>
        </div>
      </div>
    </div>
  </div>
